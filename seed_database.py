def seed_database():
    print("=" * 65)
    print("  🚀 PRISM AI — CHROMADB VECTOR DATABASE SEEDER")
    print("=" * 65)
    
    client = get_chroma_client()
    ef = get_embedding_function()
    
    # -------------------------------------------------------------
    # 1. Seed Research Memories
    # -------------------------------------------------------------
    print("\n[*] Step 1: Seeding Research Memories into ChromaDB...")
    seeded_memory_count = 0
    
    for item in SAMPLE_RESEARCH_MEMORIES:
        topic = item["topic"]
        workspace = item["workspace"]
        summary = item["summary"]
        critique = item["critique"]
        full_research = item["full_research"]
        
        doc_id = f"mem_seed_{uuid.uuid4().hex[:8]}"
        combined_doc = f"TOPIC: {topic}\n\nSUMMARY:\n{summary}\n\nCRITIQUE:\n{json.dumps(critique)}\n\nFULL RESEARCH:\n{full_research}"
        metadata = {
            "topic": topic,
            "timestamp": datetime.now().isoformat(),
            "type": "comprehensive_research",
            "score": str(critique.get("score", 8.5)),
            "workspace": workspace,
            "seeded": "true"
        }
        
        store_research_memory(
            doc_id=doc_id,
            document_text=combined_doc,
            metadata=metadata,
            workspace=workspace
        )
        seeded_memory_count += 1
        print(f"  [✓] Seeded memory: '{topic}' (Workspace: '{workspace}')")

    # -------------------------------------------------------------
    # 2. Seed PDF Document Vectors
    # -------------------------------------------------------------
    print("\n[*] Step 2: Seeding Academic PDF Vectors into ChromaDB...")
    pdf_collection_name = get_collection_name_for_workspace("default", suffix="_pdfs")
    pdf_collection = client.get_or_create_collection(
        name=pdf_collection_name,
        embedding_function=ef,
        metadata={"hnsw:space": "cosine"}
    )
    
    batch_docs = []
    batch_metas = []
    batch_ids = []
    
    for idx, chunk in enumerate(SAMPLE_PDF_CHUNKS):
        c_id = f"pdf_seed_{idx}_{uuid.uuid4().hex[:6]}"
        batch_ids.append(c_id)
        batch_docs.append(chunk["text"])
        batch_metas.append({
            "source_file": chunk["filename"],
            "title": chunk["title"],
            "section": chunk["section"],
            "chunk_index": str(idx),
            "timestamp": datetime.now().isoformat(),
            "workspace": "default",
            "seeded": "true"
        })
        
    pdf_collection.add(
        documents=batch_docs,
        metadatas=batch_metas,
        ids=batch_ids
    )
    print(f"  [✓] Seeded {len(batch_docs)} PDF chunks for '{SAMPLE_PDF_CHUNKS[0]['filename']}'")

    # -------------------------------------------------------------
    # 3. Update database/pdf_metadata.json
    # -------------------------------------------------------------
    print("\n[*] Step 3: Registering PDF in database/pdf_metadata.json...")
    db_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), "database")
    os.makedirs(db_dir, exist_ok=True)
    meta_path = os.path.join(db_dir, "pdf_metadata.json")
    
    existing_meta = []
    if os.path.exists(meta_path):
        try:
            with open(meta_path, "r", encoding="utf-8") as f:
                existing_meta = json.load(f)
        except Exception:
            existing_meta = []
            
    # Check if already present
    already_present = any(m.get("filename") == SAMPLE_PDF_CHUNKS[0]["filename"] for m in existing_meta)
    if not already_present:
        existing_meta.append({
            "filename": SAMPLE_PDF_CHUNKS[0]["filename"],
            "title": SAMPLE_PDF_CHUNKS[0]["title"],
            "chunk_count": len(SAMPLE_PDF_CHUNKS),
            "sections": ["Header/Title", "Abstract", "1. Introduction", "2. Multi-Agent Framework", "3. Role Assignment & Prompting", "4. Experimental Results", "5. Ablation Studies", "6. Conclusion & Future Work"],
            "table_count": 0,
            "reference_count": 3,
            "summary": "This seminal academic paper introduces communicative multi-agent coordination architectures for complex software and literature synthesis, achieving 42.6% accuracy improvements over monolithic models.",
            "timestamp": datetime.now().isoformat(),
            "workspace": "default"
        })
        with open(meta_path, "w", encoding="utf-8") as f:
            json.dump(existing_meta, f, indent=2)
        print(f"  [✓] Saved metadata entry for '{SAMPLE_PDF_CHUNKS[0]['filename']}'")
    else:
        print(f"  [i] Metadata for '{SAMPLE_PDF_CHUNKS[0]['filename']}' already registered.")

    # -------------------------------------------------------------
    # 4. Verification Summary
    # -------------------------------------------------------------
    print("\n" + "=" * 65)
    print("  📊 CHROMADB SEEDING COMPLETE & VERIFIED")
    print("=" * 65)
    
    cols = client.list_collections()
    for col in cols:
        print(f"  • Collection: '{col.name}' — {col.count()} vector embeddings stored")
        
    print(f"\n  [✓] Total Research Memories Seeded : {seeded_memory_count}")
    print(f"  [✓] Total PDF Chunks Seeded       : {len(SAMPLE_PDF_CHUNKS)}")
    print(f"  [✓] Active Workspaces Available   : default, ai_research")
    print("\n  Your ChromaDB vector database is now fully populated!")
    print("  When you open the UI:")
    print("    1. 'Memory Bank' tab will display the seeded research topics.")
    print("    2. 'PDF Chat' tab will have an indexed paper ready for Q&A.")
    print("=" * 65 + "\n")

if __name__ == "__main__":
    seed_database()
